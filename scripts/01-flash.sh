#!/usr/bin/env bash
# =============================================================================
#  PHASE 0.7 / 0.8 — Flash the SD card with firstrun.sh, then eject.
#  Root work happens inside osascript (native Touch ID / password dialog).
#  Usage: bash scripts/01-flash.sh
# =============================================================================
set -Eeuo pipefail
source "/Users/basestar/Survival-Pi/scripts/lib-disk-guard.sh"

ROOT="/Users/basestar/Survival-Pi"
IMG="$ROOT/staging/raspios_lite_arm64.img.xz"
FIRSTRUN="$ROOT/staging/firstrun.sh"
IMAGER="/Applications/Raspberry Pi Imager.app/Contents/MacOS/rpi-imager"
HELPER="$ROOT/scripts/_flash-helper.sh"
LOG="$ROOT/logs/flash.log"
DONE="$ROOT/logs/.flash.done"

# ---- pre-flight -------------------------------------------------------------
[[ -f "$IMAGER" ]]   || ark_die "Raspberry Pi Imager not installed at $IMAGER"
[[ -f "$IMG" ]]      || ark_die "OS image missing: $IMG"
[[ -f "$FIRSTRUN" ]] || ark_die "firstrun.sh missing — run scripts/make-firstrun.sh first"
bash -n "$FIRSTRUN"  || ark_die "firstrun.sh fails bash -n"
mkdir -p "$ROOT/logs"

echo
ark_show_disk_list >&2
echo
SD_DEV=$(ark_assert_sd_card)          # aborts hard if unsafe / absent
RAW="/dev/r${SD_DEV}"
PLAIN="/dev/${SD_DEV}"
# NB: rpi-imager's Qt6 build matches drives by /dev/diskN, not /dev/rdiskN —
# handing it the raw node makes it refuse with "not in list of removable
# volumes". Keep RAW only for the messages.
ark_ok "Guard passed → writing to $PLAIN"
echo

# ---- unmount (non destructive) ---------------------------------------------
ark_info "Unmounting $PLAIN (not ejecting yet)…"
diskutil unmountDisk "$PLAIN" >/dev/null 2>&1 || ark_warn "unmountDisk reported a problem (continuing; imager will re-check)"

# ---- build the privileged helper -------------------------------------------
# Written to disk so the AppleScript string stays trivial (no quoting hell).
cat > "$HELPER" <<EOF
#!/bin/bash
# generated by 01-flash.sh — safe to delete
exec >"$LOG" 2>&1
NOW() { date -u +%Y-%m-%dT%H:%M:%SZ; }   # BSD date has no -I on macOS
echo "===== ARK flash start \$(NOW) ====="
echo "image : $IMG"
echo "device: $PLAIN"
rm -f "$DONE"
"$IMAGER" --cli --disable-eject --first-run-script "$FIRSTRUN" "$IMG" "$PLAIN"
rc=\$?
echo "===== ARK flash end rc=\$rc \$(NOW) ====="
echo "\$rc" > "$DONE"
sync
exit \$rc
EOF
chmod 700 "$HELPER"

# ---- run it as root via the native macOS auth dialog -----------------------
# osascript runs *synchronously* inside the privileged dialog, but we launch
# osascript itself in the background so this shell can keep drawing progress.
# We poll $DONE (written by the helper) and then reap osascript.
AUTHLOG="$ROOT/logs/flash-auth.log"
rm -f "$DONE" "$LOG"
: > "$AUTHLOG"
ark_info "macOS will now ask for Touch ID / your password to write to $RAW."
osascript -e "do shell script \"/bin/bash '$HELPER'\"" >"$AUTHLOG" 2>&1 &
OSA_PID=$!

ark_info "Flashing… (write + verify, typically 6–15 minutes for a 256 GB card)"
trap 'echo; ark_warn "Interrupted — check $LOG. The card may be in a partial state."' INT TERM
last=""
while :; do
  [[ -f "$DONE" ]] && break
  if ! kill -0 "$OSA_PID" 2>/dev/null; then
    sleep 1
    [[ -f "$DONE" ]] && break
    break
  fi
  if [[ -f "$LOG" ]]; then
    line=$(grep -a -o -E '[0-9]{1,3}(\.[0-9])? ?%|Write successful|Verify successful|error[^,]*|Verifying' "$LOG" | tail -1 || true)
    if [[ -n "$line" && "$line" != "$last" ]]; then printf '\r   %-70s' "$line"; last="$line"; fi
  fi
  sleep 2
done
echo

OSA_RC=0
wait "$OSA_PID" 2>/dev/null || OSA_RC=$?

if [[ ! -f "$DONE" ]]; then
  if grep -qi 'cancel' "$AUTHLOG" 2>/dev/null; then
    ark_die "Authorization was cancelled — nothing was written to $PLAIN."
  fi
  tail -20 "$AUTHLOG" >&2 || true
  tail -20 "$LOG" 2>/dev/null >&2 || true
  ark_die "The privileged flash helper did not report completion (osascript rc=$OSA_RC). Nothing was verified."
fi

RC=$(cat "$DONE" 2>/dev/null | tr -dc '0-9' || true)
if [[ "${RC:-1}" != "0" ]]; then
  tail -8 "$LOG" | tr '\r' '\n' | grep -v '^[[:space:]]*$' >&2
  if grep -q 'Error reading from storage' "$LOG" 2>/dev/null; then
    echo >&2
    ark_warn "The card DISAPPEARED from the USB bus mid-verify (kernel: disk4: I/O error)."
    ark_warn "That is a reader/card/port problem, not an image problem — the write itself reached 100%."
    ark_warn "Fix: unplug the card reader, reseat the microSD, plug it straight into the Mac"
    ark_warn "     (no hub / no extension cable), wait 5 s, confirm with:"
    ark_warn "       diskutil list external physical"
    ark_warn "Then re-run: bash $ROOT/scripts/01-flash.sh"
  fi
  ark_die "rpi-imager exited rc=${RC:-?} — see $LOG"
fi
ark_ok "Write + verify successful"

# ---- eject cleanly ---------------------------------------------------------
ark_info "Ejecting $PLAIN"
diskutil eject "$PLAIN" >/dev/null 2>&1 || ark_warn "eject reported a problem; you can unplug now."
ark_ok "SD card ejected — safe to remove"
echo
echo "==============================================================="
echo "  NEXT: 1) pull the card out of the Mac"
echo "        2) insert it into the Raspberry Pi 4"
echo "        3) plug in the USB-C power supply"
echo "  Then run:  bash $ROOT/scripts/02-wait-for-pi.sh"
echo "==============================================================="
